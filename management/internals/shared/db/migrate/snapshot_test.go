var equivalenceCases = map[string]schemaPair{
	"column order": both(
		"CREATE TABLE users (id bigint PRIMARY KEY, a text, b text);",
		"CREATE TABLE users (b text, a text, id bigint PRIMARY KEY);",
	),
	"constraint order": both(
		withPair(", CONSTRAINT chk_ab CHECK (a <> b), CONSTRAINT chk_ax CHECK (a <> 'x')"),
		withPair(", CONSTRAINT chk_ax CHECK (a <> 'x'), CONSTRAINT chk_ab CHECK (a <> b)"),
	),
	"foreign key actions spelled out": both(
		withFK(""),
		withFK(" ON DELETE NO ACTION ON UPDATE NO ACTION"),
	),
	"explicit ascending index": both(
		tableWithIdxA+"CREATE INDEX idx_items_a ON items (a);",
		tableWithIdxA+"CREATE INDEX idx_items_a ON items (a ASC);",
	),
	"if not exists index": both(
		tableWithIdxA+"CREATE INDEX idx_items_a ON items (a);",
		tableWithIdxA+"CREATE INDEX IF NOT EXISTS idx_items_a ON items (a);",
	),
	"identifier quoting": {
		db.SqliteStoreEngine: {
			"CREATE TABLE `users` (`id` bigint PRIMARY KEY, `a`  text   NOT NULL, CHECK (`a` <> 'x'));",
			`CREATE TABLE "users" ("id" bigint PRIMARY KEY, "a" text NOT NULL, CHECK ("a"<>'x'));`,
		},
		db.PostgresStoreEngine: {
			`CREATE TABLE "users" ("id" bigint PRIMARY KEY, "a" text NOT NULL, CHECK ("a" <> 'x'));`,
			"CREATE TABLE users (id bigint PRIMARY KEY, a text NOT NULL, CHECK (a <> 'x'));",
		},
	},
	"added column": both(
		"CREATE TABLE users (id bigint PRIMARY KEY, a text, b text NOT NULL DEFAULT 'x');",
		"CREATE TABLE users (id bigint PRIMARY KEY, a text); ALTER TABLE users ADD COLUMN b text NOT NULL DEFAULT 'x';",
	),
}

func execScript(t *testing.T, gormDB *gorm.DB, script string) {
	t.Helper()
	for statement := range strings.SplitSeq(script, ";") {
		if strings.TrimSpace(statement) == "" {
			continue
		}
		require.NoError(t, gormDB.Exec(statement).Error, statement)
	}
}

func snapshotOf(t *testing.T, open openFunc, script string) map[string]TableSchema {
	t.Helper()
	gormDB, closeDB := open()
	defer closeDB()
	execScript(t, gormDB, script)
	snapshot, err := SchemaSnapshot(gormDB)
	require.NoError(t, err)
	return snapshot
}

// openFunc opens an empty database and returns it with the function that releases it.
type openFunc func() (*gorm.DB, func())

func runSnapshotCases(t *testing.T, engine db.Engine, open openFunc) {
	t.Run("differences", func(t *testing.T) {
		for name, pair := range differenceCases {
			scripts, ok := pair[engine]
			if !ok {
				continue
			}
			t.Run(name, func(t *testing.T) {
				base := snapshotOf(t, open, scripts[0])
				changed := snapshotOf(t, open, scripts[1])
				assert.NotEqual(t, base, changed, "the snapshot must tell the schemas apart")
				assert.Equal(t, base, snapshotOf(t, open, scripts[0]), "the snapshot must be deterministic")
			})
		}
	})
	t.Run("equivalences", func(t *testing.T) {
		for name, pair := range equivalenceCases {
			scripts, ok := pair[engine]
			if !ok {
				continue
			}
			t.Run(name, func(t *testing.T) {
				assert.Equal(t, snapshotOf(t, open, scripts[0]), snapshotOf(t, open, scripts[1]))
			})
		}
	})
}

func TestSchemaSnapshot_Sqlite(t *testing.T) {
	open := func() (*gorm.DB, func()) {
		conn, err := db.OpenSqliteFile(context.Background(), t.TempDir(), db.SqliteFileName)
		require.NoError(t, err)
		return conn.DB(nil), func() { _ = conn.Close() }
	}
	runSnapshotCases(t, db.SqliteStoreEngine, open)
}

func TestSchemaSnapshot_Postgres(t *testing.T) {
	dsn := postgresDSN(t)
	admin := openPostgres(t, dsn)
	open := func() (*gorm.DB, func()) {
		name := "snapshot_" + xid.New().String()
		require.NoError(t, admin.DB(nil).Exec("CREATE DATABASE "+name).Error)
		u, err := url.Parse(dsn)
		require.NoError(t, err)
		u.Path = "/" + name
		conn, err := db.OpenPostgres(context.Background(), u.String(), db.DefaultPoolConfig)
		require.NoError(t, err)
		return conn.DB(nil), func() {
			_ = conn.Close()
			_ = admin.DB(nil).Exec("DROP DATABASE IF EXISTS " + name + " WITH (FORCE)").Error
		}
	}
	runSnapshotCases(t, db.PostgresStoreEngine, open)
}
