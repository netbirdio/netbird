type schemaPair map[db.Engine][2]string

// both returns the pair for engines that share the DDL syntax.
func both(base, changed string) schemaPair {
	pair := [2]string{base, changed}
	return schemaPair{db.SqliteStoreEngine: pair, db.PostgresStoreEngine: pair}
}

const (
	parentTable   = "CREATE TABLE parents (id bigint PRIMARY KEY);"
	childWithFK   = parentTable + "CREATE TABLE children (id bigint PRIMARY KEY, parent_id bigint, CONSTRAINT fk_children_parent FOREIGN KEY (parent_id) REFERENCES parents(id)%s);"
	pairTable     = "CREATE TABLE pairs (id bigint PRIMARY KEY, a text, b text%s);"
	namesTable    = "CREATE TABLE names (id bigint PRIMARY KEY, name %s);"
	tableWithIdxA = "CREATE TABLE items (id bigint PRIMARY KEY, a text, b text, active boolean);"
)

func withFK(clause string) string  { return strings.Replace(childWithFK, "%s", clause, 1) }
func withPair(extra string) string { return strings.Replace(pairTable, "%s", extra, 1) }
func withName(typ string) string   { return strings.Replace(namesTable, "%s", typ, 1) }

